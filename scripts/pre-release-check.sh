#/**
# * @file pre-release-check.sh
# * @brief Authoritative release-readiness gate for cli-skills.
# * @details Executes, in fixed order, toolchain and lockfile validation, shell
# *          and Python syntax validation, the unit-test suite, release
# *          distribution generation through scripts/build.sh into a temporary
# *          release output directory outside the repository tree and outside
# *          dist/, artifact-content validation, and twine metadata validation.
# *          No dist/ entry is read, verified, or modified. An EXIT trap removes
# *          every output generated by this run, verifies the Git status and
# *          tracked diffs against pre-run snapshots, and preserves the original
# *          verification status. Any failed check exits nonzero.
# * @satisfies PRJ-014 DES-084 DES-085 DES-086 DES-087 DES-136 DES-137 DES-149
# *            DES-152 DES-153 DES-154 DES-155 DES-156 DES-157 DES-158 DES-159
# *            DES-161 DES-162 DES-163 DES-164 DES-165 DES-166 DES-167
# *            DES-173
# */

set -Eeuo pipefail

#/**
# * @brief Original script location used to resolve the repository root.
# * @details BASH_SOURCE[0] preserves the invocation path, including spaces.
# * @satisfies DES-136
# */
SCRIPT_LOCATION=${BASH_SOURCE[0]}

#/**
# * @brief Canonical directory containing this script.
# * @satisfies DES-136
# */
SCRIPT_DIRECTORY=$(cd -- "$(dirname -- "$SCRIPT_LOCATION")" && pwd -P)

#/**
# * @brief Canonical repository root, parent of the scripts directory.
# * @satisfies DES-136
# */
PROJECT_ROOT=$(cd -- "$SCRIPT_DIRECTORY/.." && pwd -P)

#/**
# * @brief Temporary release output directory receiving scripts/build.sh outputs.
# * @details Assigned in main to CHECK_DIRECTORY/release after CHECK_DIRECTORY is created. A containment guard rejects a path inside the repository tree, so the build output never reaches dist/; no dist/ entry is read, verified, or modified.
# * @satisfies DES-084 DES-173
# */
RELEASE_DIRECTORY=

#/**
# * @brief Active phase identifier reported by diagnostics and the final summary.
# */
CURRENT_PHASE=arguments

#/**
# * @brief Distribution file prefix derived from the pyproject project name.
# * @details Equals the project name with `-` replaced by `_`; validated against `^[A-Za-z0-9_]+$`.
# * @satisfies DES-152
# */
DIST_PREFIX=

#/**
# * @brief Temporary directory holding Git snapshots, the isolated uv environment, cache listings, and the release output directory.
# * @satisfies DES-162
# */
CHECK_DIRECTORY=

#/**
# * @brief Flag set to 1 after preflight passes and the pre-run snapshot is captured, enabling cleanup.
# * @satisfies DES-163
# */
CLEANUP_ENABLED=0

#/**
# * @brief Print the usage diagnostic and terminate with status 2.
# * @details The script accepts no arguments.
# * @return {never} Exits with status 2.
# * @satisfies DES-149
# */
usage() {
    printf 'Usage: scripts/pre-release-check.sh\n' >&2
    exit 2
}

#/**
# * @brief Start a named phase and report it on stdout.
# * @param phase_id {string} Stable phase identifier stored in CURRENT_PHASE.
# * @param label {string} Human-readable phase description.
# * @return {None}
# */
begin_phase() {
    CURRENT_PHASE=$1
    printf '==> [%s] %s\n' "$1" "$2"
}

#/**
# * @brief Terminate with a phase-identified diagnostic.
# * @param message {string} Failure description.
# * @return {never} Exits with status 1; the EXIT trap performs cleanup.
# * @satisfies DES-165
# */
fail() {
    printf 'ERROR: [%s] %s\n' "$CURRENT_PHASE" "$1" >&2
    exit 1
}

#/**
# * @brief Report an unhandled failing command with its phase and exit status.
# * @param status {int} Exit status of the failing command.
# * @param command {string} Text of the failing command from BASH_COMMAND.
# * @return {never} Exits with the failing status.
# * @satisfies DES-165
# */
on_error() {
    printf 'ERROR: [%s] command failed with status %s: %s\n' "$CURRENT_PHASE" "$1" "$2" >&2
    exit "$1"
}

#/**
# * @brief Verify that every required executable is resolvable.
# * @details Collects every missing executable before failing. Complexity O(R) for R required tools.
# * @return {None}
# * @throws {SystemExit} Via `fail` when any executable is missing.
# * @satisfies DES-137
# */
require_executables() {
    local tool
    local -a missing=()
    for tool in git uv mktemp find cmp rm rmdir sed dirname basename; do
        if ! command -v "$tool" >/dev/null 2>&1; then
            missing+=("$tool")
        fi
    done
    if (( ${#missing[@]} > 0 )); then
        fail "missing required executables: ${missing[*]}"
    fi
}

#/**
# * @brief Verify the project files required by the release gate.
# * @details Requires pyproject.toml, uv.lock, the release workflow, src/cli_skills, tests, and an executable scripts/build.sh.
# * @return {None}
# * @throws {SystemExit} Via `fail` when any required entry is missing.
# * @satisfies DES-153
# */
require_project_files() {
    if [[ ! -f "$PROJECT_ROOT/pyproject.toml" || ! -f "$PROJECT_ROOT/uv.lock" ]]; then
        fail "pyproject.toml and uv.lock are required"
    fi
    if [[ ! -f "$PROJECT_ROOT/.github/workflows/release-pypi.yml" ]]; then
        fail ".github/workflows/release-pypi.yml is required"
    fi
    if [[ ! -d "$PROJECT_ROOT/src/cli_skills" || ! -d "$PROJECT_ROOT/tests" ]]; then
        fail "src/cli_skills and tests directories are required"
    fi
    if [[ ! -x "$PROJECT_ROOT/scripts/build.sh" ]]; then
        fail "scripts/build.sh must exist and be executable"
    fi
}

#/**
# * @brief Derive the distribution file prefix from the pyproject project name.
# * @details Reads the single `name = "..."` line of pyproject.toml and sets DIST_PREFIX with `-` replaced by `_`.
# * @return {None}
# * @throws {SystemExit} Via `fail` when the name is absent, ambiguous, or unsupported.
# * @satisfies DES-152
# */
resolve_project_prefix() {
    local names
    names=$(sed -n 's/^name = "\([^"]*\)"$/\1/p' "$PROJECT_ROOT/pyproject.toml")
    if [[ -z $names || $names == *$'\n'* ]]; then
        fail "pyproject.toml must declare exactly one project name"
    fi
    DIST_PREFIX=${names//-/_}
    if [[ ! $DIST_PREFIX =~ ^[A-Za-z0-9_]+$ ]]; then
        fail "unsupported distribution name: $names"
    fi
}

#/**
# * @brief Refuse to start when a build/ entry from an earlier run exists.
# * @details Aborts when build/ exists in the repository root. dist/ is not inspected because this script never writes to it. Nothing is modified.
# * @return {None}
# * @throws {SystemExit} Via `fail` when build/ exists.
# * @satisfies DES-152 DES-173
# */
check_release_state() {
    if [[ -e $PROJECT_ROOT/build || -L $PROJECT_ROOT/build ]]; then
        fail "pre-existing build/ entry prevents safe cleanup; remove it before running the gate"
    fi
}

#/**
# * @brief Remove untracked Python cache and egg-info directories under src/ and tests/.
# * @details Enumerates `__pycache__` and `*.egg-info` directories with `find -prune`, writes the listing to CHECK_DIRECTORY, refuses any directory containing a Git-tracked path, and removes the others with `rm -rf --`. Complexity O(D) for D directories.
# * @return {int} 0 when every cache directory is removed; 1 on enumeration failure, tracked content, or removal failure.
# * @satisfies DES-167 DES-087
# */
remove_python_caches() {
    local path relative tracked
    local listing=$CHECK_DIRECTORY/python-caches
    if ! find "$PROJECT_ROOT/src" "$PROJECT_ROOT/tests" -type d \( -name '__pycache__' -o -name '*.egg-info' \) -prune -print0 > "$listing"; then
        printf 'ERROR: [%s] could not enumerate Python cache directories.\n' "$CURRENT_PHASE" >&2
        return 1
    fi
    while IFS= read -r -d '' path; do
        relative=${path#"$PROJECT_ROOT"/}
        if ! tracked=$(git -C "$PROJECT_ROOT" ls-files -- "$relative"); then
            printf 'ERROR: [%s] could not query Git for %s.\n' "$CURRENT_PHASE" "$relative" >&2
            return 1
        fi
        if [[ -n $tracked ]]; then
            printf 'ERROR: [%s] generated cache directory contains tracked files: %s\n' "$CURRENT_PHASE" "$relative" >&2
            return 1
        fi
        if ! rm -rf -- "$path"; then
            printf 'ERROR: [%s] could not remove cache directory: %s\n' "$CURRENT_PHASE" "$relative" >&2
            return 1
        fi
    done < "$listing"
    return 0
}

#/**
# * @brief Capture the Git status, unstaged diff, and staged diff into CHECK_DIRECTORY.
# * @details Writes `status.<stage>`, `unstaged.<stage>`, and `staged.<stage>` files. The status uses `--untracked-files=all --ignored` so ignored outputs are included.
# * @param stage {string} `before` or `after`.
# * @return {int} 0 when every snapshot is captured; 1 otherwise.
# * @satisfies DES-162
# */
capture_snapshot() {
    local stage=$1
    if ! git -C "$PROJECT_ROOT" status --porcelain --untracked-files=all --ignored > "$CHECK_DIRECTORY/status.$stage"; then
        return 1
    fi
    if ! git -C "$PROJECT_ROOT" diff --binary > "$CHECK_DIRECTORY/unstaged.$stage"; then
        return 1
    fi
    if ! git -C "$PROJECT_ROOT" diff --cached --binary > "$CHECK_DIRECTORY/staged.$stage"; then
        return 1
    fi
    return 0
}

#/**
# * @brief Compare the final Git state with the pre-run snapshots.
# * @details Captures the after-state and compares the status, unstaged diff, and staged diff byte-for-byte with their before-state files. Complexity O(S) for S snapshot bytes.
# * @return {int} 0 when every state matches; 1 on capture failure or mismatch.
# * @satisfies DES-162
# */
verify_repository_state() {
    local item
    if ! capture_snapshot after; then
        printf 'ERROR: [cleanup] could not capture the final Git state.\n' >&2
        return 1
    fi
    for item in status unstaged staged; do
        if ! cmp -s -- "$CHECK_DIRECTORY/$item.before" "$CHECK_DIRECTORY/$item.after"; then
            printf 'ERROR: [cleanup] Git %s state differs from the pre-run snapshot.\n' "$item" >&2
            return 1
        fi
    done
    return 0
}

#/**
# * @brief Verify that every shell script under scripts/ parses.
# * @details Runs `bash -n` on each `scripts/*.sh` file. Fails when no script exists.
# * @return {None}
# * @throws {SystemExit} Via `fail` when no script is found; `bash -n` failures exit through `on_error`.
# * @satisfies DES-155
# */
check_shell_syntax() {
    local script
    local -a scripts=()
    shopt -s nullglob
    scripts=("$PROJECT_ROOT"/scripts/*.sh)
    shopt -u nullglob
    if (( ${#scripts[@]} == 0 )); then
        fail "no shell scripts found under scripts/"
    fi
    for script in "${scripts[@]}"; do
        bash -n "$script"
        printf 'bash -n OK: %s\n' "${script#"$PROJECT_ROOT"/}"
    done
}

#/**
# * @brief Run the twine metadata check on the generated sdist and wheel.
# * @details Executes `twine check` through an isolated uv environment with `--with twine`, using the exact artifact paths found in RELEASE_DIRECTORY. Complexity O(1) plus twine processing.
# * @return {None}
# * @satisfies DES-085
# */
check_twine_metadata() {
    local -a artifacts=()
    shopt -s nullglob
    artifacts=("$RELEASE_DIRECTORY/$DIST_PREFIX"-*.tar.gz "$RELEASE_DIRECTORY/$DIST_PREFIX"-*.whl)
    shopt -u nullglob
    uv run --no-project --with twine python -m twine check -- "${artifacts[@]}"
}

#/**
# * @brief Remove build intermediates, caches, and verify the Git state.
# * @details Removes build/, removes untracked Python caches, and verifies the Git status and tracked diffs against the pre-run snapshots. The temporary release output directory is removed by `finish` together with CHECK_DIRECTORY; tracked dist/ entries are never read or modified. Returns nonzero on any failure without invoking `fail`, so the EXIT handler keeps the status.
# * @return {int} 0 when cleanup and integrity verification succeed; 1 otherwise.
# * @satisfies DES-087 DES-162 DES-164 DES-173
# */
cleanup_repository() {
    local status=0
    if [[ -e $PROJECT_ROOT/build || -L $PROJECT_ROOT/build ]]; then
        if ! rm -rf -- "$PROJECT_ROOT/build"; then
            printf 'ERROR: [cleanup] could not remove generated build/.\n' >&2
            status=1
        fi
    fi
    if ! remove_python_caches; then
        status=1
    fi
    if ! verify_repository_state; then
        status=1
    fi
    return "$status"
}

#/**
# * @brief Terminate the script while preserving the original status and enforcing cleanup.
# * @details Runs as the EXIT trap. Captures the status and failing phase first, clears all traps, runs cleanup when CLEANUP_ENABLED is 1, reports cleanup failure as status 1 only when the checks succeeded, removes CHECK_DIRECTORY, and prints a PASS or phase-identified FAIL summary. Complexity O(1) plus cleanup.
# * @return {never} Exits with the final status.
# * @satisfies DES-163 DES-164 DES-165
# */
finish() {
    local status=$?
    local failed_phase=$CURRENT_PHASE
    trap - EXIT ERR INT TERM HUP
    if (( CLEANUP_ENABLED == 1 )); then
        CURRENT_PHASE=cleanup
        if ! cleanup_repository; then
            if (( status == 0 )); then
                status=1
                failed_phase=cleanup
            fi
        fi
    fi
    if [[ -n $CHECK_DIRECTORY && -e $CHECK_DIRECTORY ]]; then
        if ! rm -rf -- "$CHECK_DIRECTORY"; then
            printf 'ERROR: [cleanup] could not remove temporary check directory: %s\n' "$CHECK_DIRECTORY" >&2
            if (( status == 0 )); then
                status=1
                failed_phase=cleanup
            fi
        fi
    fi
    if (( status == 0 )); then
        printf 'Pre-release checks: PASS; cleanup: PASS.\n'
    else
        printf 'Pre-release checks: FAIL at phase %s (status %d).\n' "$failed_phase" "$status" >&2
    fi
    exit "$status"
}

#/**
# * @brief Execute the release-readiness sequence.
# * @details Order: preflight (refusals, cache removal, snapshot), toolchain and lockfile, syntax, unit tests, cache removal, build through scripts/build.sh, artifact content validation, and twine metadata. Cleanup runs in the EXIT trap.
# * @return {None}
# * @throws {SystemExit} Via `fail`, `on_error`, or the EXIT trap on any failed check.
# * @satisfies PRJ-014 DES-084 DES-085 DES-086 DES-154 DES-156 DES-157 DES-158 DES-159 DES-161
# */
main() {
    if (( $# != 0 )); then
        usage
    fi
    cd -- "$PROJECT_ROOT"
    begin_phase preflight "Validating executables, project files, and release state"
    require_executables
    require_project_files
    resolve_project_prefix
    check_release_state
    CHECK_DIRECTORY=$(mktemp -d "${TMPDIR:-/tmp}/cli-skills-pre-release.XXXXXX")
    RELEASE_DIRECTORY=$CHECK_DIRECTORY/release
    case $RELEASE_DIRECTORY in
        "$PROJECT_ROOT"/*)
            fail "temporary release directory must be outside the repository tree: $RELEASE_DIRECTORY"
            ;;
    esac
    export UV_PROJECT_ENVIRONMENT="$CHECK_DIRECTORY/venv"
    if ! remove_python_caches; then
        fail "untracked Python cache directories could not be removed safely"
    fi
    if ! capture_snapshot before; then
        fail "could not capture the pre-run Git state"
    fi
    CLEANUP_ENABLED=1

    begin_phase toolchain "Validating toolchain and lockfile consistency"
    uv --version
    git --version
    uv lock --check

    begin_phase syntax "Checking shell syntax, Python syntax, and pyproject.toml parsing"
    check_shell_syntax
    uv run --no-project python - "$PROJECT_ROOT" <<'PY'
import ast
import sys
import tomllib
from pathlib import Path

root = Path(sys.argv[1])
tomllib.loads((root / "pyproject.toml").read_text(encoding="utf-8"))
sources = sorted(path for directory in ("src", "tests") for path in (root / directory).rglob("*.py"))
if not sources:
    raise SystemExit("no Python sources found under src/ or tests/")
for path in sources:
    ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
print(f"Python syntax OK: {len(sources)} files; pyproject.toml OK")
PY

    begin_phase unit-tests "Running the unit-test suite"
    uv run python -m unittest discover -s tests

    begin_phase cache-reset "Removing Python caches before distribution generation"
    if ! remove_python_caches; then
        fail "Python caches could not be removed before distribution generation"
    fi

    begin_phase build "Generating release distributions with scripts/build.sh"
    "$PROJECT_ROOT/scripts/build.sh" --output-dir "$RELEASE_DIRECTORY"

    begin_phase artifacts "Validating release output artifact content and twine metadata"
    uv run --no-project python - "$PROJECT_ROOT" "$RELEASE_DIRECTORY" <<'PY'
import configparser
import json
import sys
import tarfile
import tomllib
import zipfile
from pathlib import Path

root = Path(sys.argv[1])
release_directory = Path(sys.argv[2])
project = tomllib.loads((root / "pyproject.toml").read_text(encoding="utf-8"))["project"]
prefix = project["name"].replace("-", "_")
version = project["version"]
sdists = sorted(release_directory.glob(f"{prefix}-*.tar.gz"))
wheels = sorted(release_directory.glob(f"{prefix}-*.whl"))
if len(sdists) != 1 or len(wheels) != 1:
    raise SystemExit(f"expected one sdist and one wheel in the release output directory, found {len(sdists)} and {len(wheels)}")
sdist, wheel = sdists[0], wheels[0]
if sdist.name != f"{prefix}-{version}.tar.gz" or not wheel.name.startswith(f"{prefix}-{version}-"):
    raise SystemExit(f"artifact names differ from pyproject version {version}: {sdist.name}, {wheel.name}")

resources = root / "src" / "resources"
manifest = json.loads((resources / "manifest.json").read_text(encoding="utf-8"))
required = {"cli_skills/__main__.py", "cli_skills/core.py"}
required |= {
    "cli_skills/resources/" + path.relative_to(resources).as_posix()
    for path in resources.rglob("*")
    if path.is_file() and "__pycache__" not in path.parts
}
required |= {"cli_skills/resources/" + entry["file"] for entry in manifest["skills"]}
with zipfile.ZipFile(wheel) as archive:
    if archive.testzip() is not None:
        raise SystemExit("wheel archive is corrupt")
    members = set(archive.namelist())
    missing = sorted(required - members)
    if missing:
        raise SystemExit(f"wheel is missing files: {missing}")
    stray = sorted(name for name in members if name.startswith("resources/"))
    if stray:
        raise SystemExit(f"wheel installs a top-level resources package: {stray[:3]}")
    entry_points = sorted(name for name in members if name.endswith(".dist-info/entry_points.txt"))
    if len(entry_points) != 1:
        raise SystemExit("wheel must contain exactly one entry_points.txt")
    parser = configparser.ConfigParser(interpolation=None)
    parser.optionxform = str
    parser.read_string(archive.read(entry_points[0]).decode("utf-8"))
    scripts = dict(parser["console_scripts"]) if parser.has_section("console_scripts") else {}
    for command in ("cli-skills", "skills"):
        if scripts.get(command) != "cli_skills.core:main":
            raise SystemExit(f"console script {command} is not bound to cli_skills.core:main")
base = f"{prefix}-{version}/"
with tarfile.open(sdist, "r:gz") as archive:
    names = set(archive.getnames())
for relative in ("pyproject.toml", "README.md", "LICENSE", "src/cli_skills/core.py", "src/resources/manifest.json"):
    if base + relative not in names:
        raise SystemExit(f"sdist is missing {relative}")
print(f"Artifact content OK: {sdist.name}, {wheel.name}")
PY
    check_twine_metadata

    printf '==> All release checks passed.\n'
}

trap finish EXIT
trap 'on_error "$?" "$BASH_COMMAND"' ERR
trap 'exit 129' HUP
trap 'exit 130' INT
trap 'exit 143' TERM

main "$@"
